/** Normalizes string for fuzzy comparison */
export function norm(s: string): string {
  return s.toLowerCase().replace(/[\s\-.'’‘]/g, "");
}

/** Check if string has Bengali letters */
export function hasBangla(s: string): boolean {
  return /[\u0980-\u09FF]/.test(s);
}

/** Finds bank or MFS from name */
export function findBank(name: string): BankInfo | undefined {
  const n = norm(name);
  if (!n) return undefined;
  return [...MFS_LIST, ...BANK_LIST].find(
    (b) => norm(b.en) === n || norm(b.bn) === n
  );
}

/** Suggests banks or MFS based on user typing */
export function bankSuggestions(type: string, typed: string): BankInfo[] {
  const list = type === "mobile" ? MFS_LIST : type === "bank" ? BANK_LIST : [];
  const q = norm(typed);
  if (!q) return [];

  return list
    .filter((b) => norm(b.en).includes(q) || norm(b.bn).includes(q))
    .filter((b) => {
      const matchName = hasBangla(typed) ? b.bn : b.en;
      return norm(matchName) !== q;
    })
    .sort((a, b) => {
      const aStarts = norm(a.en).startsWith(q) || norm(a.bn).startsWith(q);
      const bStarts = norm(b.en).startsWith(q) || norm(b.bn).startsWith(q);
      if (aStarts && !bStarts) return -1;
      if (!aStarts && bStarts) return 1;
      return 0;
    })
    .slice(0, 6);
}
